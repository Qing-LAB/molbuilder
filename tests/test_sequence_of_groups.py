"""A sequence of groups sent to a queue (`execution/job-system.md` § 6.0, *A
sequence of groups*): the one header prep writes for it, and the job its
launch sends -- on a machine whose record names two queues and whose
`sbatch` writes each call down and refuses it (`support.road.
a_machine_with_queues`: no scheduler text in the basic tests).  Nothing
here runs an engine; the road with SIESTA is `test_sequence_of_groups_e2e`.

API-LEVEL: the header, the walk and the record are generated by the verbs
and read back -- the header's directive lines through the scheduler kind
that wrote them, the record through its one reader.

THE SILENT FAILURES IT GUARDS: a sequence's allocation smaller than one of
its groups asks for (a group then runs short of ranks inside the job), or
its wall one group's instead of every group's (the job killed before the
last group); a job whose runs cannot name the job (the walk not passing its
sequence and its address); a sequence sent under no header prep wrote.
"""

import pytest

from support.road import (a_machine_with_queues, calls_made,
                          describe_calculation, jobset, read_request,
                          write_request)


def _queues():
    from molbuilder.scheduler import Domain
    return [Domain(name="debug", partition="htc", qos="debug",
                   max_time="0-00:15:00"),
            Domain(name="htc", partition="htc", qos="public",
                   max_time="0-04:00:00")]


def _cards(bundle, **by_stage):
    """Each stage's own run card, as Task setup writes it -- the job
    request's `stages.<name>.execution`."""
    request = read_request(bundle)
    request["allocation"] = {"time": "0-01:00:00", "mem": "8G"}
    for name, entry in request["stages"].items():
        entry["execution"] = {**entry.get("execution", {}),
                              **by_stage.get(name, {})}
    write_request(bundle, request)


@pytest.fixture
def cluster(tmp_path, monkeypatch):
    """The H2 ladder -- `coarse`, group 1; `medium`, group 2, building on
    it -- on the two-queue machine: ``(bundle, calls)``."""
    calls = a_machine_with_queues(tmp_path, monkeypatch, _queues())
    return describe_calculation(tmp_path, monkeypatch), calls


def _header_value(header, name):
    from molbuilder.scheduler.kinds import kind
    kind = kind("slurm")
    return kind.directive_value(name, kind.directive_lines_of(
        header.read_text()))


@pytest.mark.parametrize("case", [
    # each group's own request; the sequence's: the largest, walls summed
    {"cards": {"coarse": {"mpi_np": 2}, "medium": {"mpi_np": 4}},
     "ntasks": "4", "wall": "0-02:00:00"},
    {"cards": {"coarse": {"mpi_np": 4, "time": "0-00:30:00"},
               "medium": {"mpi_np": 2}},
     "ntasks": "4", "wall": "0-01:30:00"},
])
def test_one_job_asks_the_largest_request_and_every_wall(cluster, case):
    """`prep task --group 1 --group 2 --one-job` writes the sequence's one
    header: one queue, the LARGEST ranks any group asks for, the walls
    SUMMED -- a group asking less runs with its own card inside it, said."""
    bundle, _calls = cluster
    _cards(bundle, **case["cards"])
    r = jobset("prep", "task", "--group", "1", "--group", "2", "--one-job",
               "--domain", "htc", "--bundle", bundle, "--target", "this")
    assert r.exit_code == 0, r.output
    header = bundle / "launch" / "H2_sequence-01_coarse-02_medium.sbatch"
    assert header.is_file(), r.output
    assert _header_value(header, "ranks") == case["ntasks"], \
        header.read_text()
    assert _header_value(header, "wall") == case["wall"], header.read_text()
    assert "runs with its own card inside it" in r.output, r.output


def test_the_job_sent_is_prep_s_header_and_its_record(cluster):
    """`launch task --group 1 --group 2 --mode submit` sends the header prep
    wrote, from the calculation's folder, after writing the sequence's walk
    and its launch record -- what each run inside the job records of it,
    read through its one reader.  What the walk runs, each group's own
    launch recording the job, is the e2e's to show, by running it
    (`test_sequence_of_groups_e2e`)."""
    from molbuilder.jobset.sequence import read_record, record_path
    from molbuilder.runfiles import GroupNames
    bundle, calls = cluster
    _cards(bundle)
    r = jobset("prep", "task", "--group", "1", "--group", "2", "--one-job",
               "--domain", "htc", "--bundle", bundle, "--target", "this")
    assert r.exit_code == 0, r.output
    r = jobset("launch", "task", "--group", "1", "--group", "2",
               "--bundle", bundle, "--mode", "submit", "--yes")
    # THE SUITE'S `sbatch` REFUSES -- after the send's writes are carried out
    assert r.exit_code != 0, r.output
    name = "H2_sequence-01_coarse-02_medium"
    (where, argv), = calls_made(calls)
    assert where == bundle.resolve() and argv[-1] == f"launch/{name}.sbatch", \
        (where, argv)
    assert (bundle / "launch" / f"{name}.run.sh").is_file()
    rec = read_record(record_path(bundle, GroupNames(name)))
    assert ([g["number"] for g in rec.groups], rec.mode) == ([1, 2], "submit")
    assert rec.scheduler == {"kind": "slurm", "outputs_in": "launch"}, rec
    assert rec.placed_on["domain"] == "htc" and rec.job_id is None, rec


@pytest.mark.parametrize("case", [
    # R-L45: no header prep wrote for exactly these groups
    {"prep": ["--domain", "htc"], "launch": ["--mode", "submit"],
     "says": ["--one-job"]},
    # R-L45: a flag that speaks for one stage
    {"prep": ["--domain", "htc", "--one-job"],
     "launch": ["--mode", "submit", "--cold"],
     "says": ["speak for one stage"]},
    # R-P22: two queues -- each stage's own card -- are no one job
    {"cards": {"coarse": {"domain": "htc"}, "medium": {"domain": "debug"}},
     "prep": ["--one-job"], "refused_at": "prep",
     "says": ["one job sits in one queue"]},
])
def test_what_one_job_refuses(cluster, case):
    """The sequence's refusals, before anything is sent, each naming its
    way on (`job-system.md` R-L45, R-P22)."""
    bundle, calls = cluster
    _cards(bundle, **case.get("cards", {}))
    r = jobset("prep", "task", "--group", "1", "--group", "2",
               *case["prep"], "--bundle", bundle, "--target", "this")
    if case.get("refused_at") == "prep":
        assert r.exit_code != 0, r.output
        out = r.output
    else:
        assert r.exit_code == 0, r.output
        launched = jobset("launch", "task", "--group", "1", "--group", "2",
                          "--bundle", bundle, *case["launch"], "--yes")
        assert launched.exit_code != 0, launched.output
        out = launched.output
    assert all(w in out for w in case["says"]), out
    assert calls_made(calls) == []
