/* File-upload generator panel — Molbuilder-tab Source.
 *
 * Wires the Sources card's "Load from local file" panel.  Reads
 * an XYZ / PDB file from the user's disk via FileReader, posts
 * the text to ``/api/build/load`` (which accepts the same JSON
 * body whether the source came from disk or a server fetch),
 * then routes the result through ``structurePage.loadIntoCanvas``
 * so the dirty-canvas warning fires before discarding workspace
 * edits.
 *
 * "Load from project" (the existing Load-from-project panel)
 * loads files already in the project tree; this panel handles
 * files that LIVE OUTSIDE the project — typically structures
 * downloaded from a paper or generated by another tool that
 * haven't been imported into a molbuilder project yet.
 *
 * Flow:
 *   1. User picks a file via #file-upload-input.
 *   2. FileReader reads the text.
 *   3. POST {text, format: "auto", filename: <name>} to
 *      /api/build/load.
 *   4. Route response.xyz through structurePage.loadIntoCanvas.
 *   5. Hand to ``loadStructureText`` for the viewer render.
 *
 * Source provenance: ``kind: "file"`` (matches the project-load
 * path) + ``file: <basename>`` (not a project-relative path —
 * the file isn't in a project) + ``generator_input: null``.
 *
 * Test seam: ``configure(opts)`` lets tests inject a fake
 * fetch + structurePage + viewer-loader so the Node-only
 * unit tests can drive the state machine without a real DOM.
 *
 * Design ref: docs/tabs/architecture.md § 5.1 (panel 5: file
 * upload, part of the "others" generator group).
 */
(function (root) {
    "use strict";

    var LOAD_URL = "/api/build/load";

    var _fetch         = null;
    var _structurePage = null;
    var _viewerLoader  = null;

    function configure(opts) {
        opts = opts || {};
        if (opts.fetch)         _fetch         = opts.fetch;
        if (opts.structurePage) _structurePage = opts.structurePage;
        if (opts.viewerLoader)  _viewerLoader  = opts.viewerLoader;
    }

    /**
     * Load a structure from raw XYZ / PDB text — typically from
     * a FileReader read in production; tests pass the text
     * directly.
     *
     * @param {string} text       the structure file content
     * @param {string} filename   the original filename
     *                            (extension drives format detect)
     * @returns {Promise<{ok: boolean,
     *                    cancelled?: boolean,
     *                    error?: string,
     *                    n_atoms?: number}>}
     */
    function loadText(text, filename) {
        if (typeof text !== "string" || !text) {
            return Promise.resolve({
                ok: false, error: "File appears to be empty." });
        }
        if (!_fetch) {
            return Promise.reject(new Error(
                "file: fetch not configured"));
        }
        if (!_structurePage) {
            return Promise.reject(new Error(
                "file: structurePage not configured"));
        }
        var safeName = typeof filename === "string" ? filename : "";
        return _fetch(LOAD_URL, {
            method:  "POST",
            headers: { "Content-Type": "application/json" },
            body:    JSON.stringify({
                text:     text,
                format:   "auto",
                filename: safeName,
            }),
        })
        .then(function (r) {
            return r.json().then(function (body) {
                return { httpOk: r.ok, body: body };
            });
        })
        .then(function (env) {
            var body = env.body || {};
            if (!env.httpOk || !body.ok) {
                return {
                    ok:    false,
                    error: body.error
                            || ("HTTP error from " + LOAD_URL),
                };
            }
            var format = (body.source_format === "pdb") ? "pdb" : "xyz";
            var payload = (format === "pdb" && body.pdb)
                ? body.pdb : body.xyz;
            return _structurePage.loadIntoCanvas(
                { source_format: format, text: payload },
                { kind: "file", file: safeName || null,
                  generator_input: null }
            ).then(function (gate) {
                if (!gate.ok) {
                    return { ok: false, cancelled: true };
                }
                if (typeof _viewerLoader === "function") {
                    var fname = safeName || "upload";
                    try {
                        var maybe = _viewerLoader(payload, fname);
                        if (maybe && typeof maybe.then === "function") {
                            return maybe.then(function () {
                                return { ok: true,
                                         n_atoms: body.n_atoms };
                            });
                        }
                    } catch (e) {
                        return {
                            ok:    false,
                            error: "Viewer failed to render: "
                                 + (e && e.message ? e.message
                                                   : String(e)),
                        };
                    }
                }
                return { ok: true, n_atoms: body.n_atoms };
            });
        })
        .catch(function (err) {
            return {
                ok:    false,
                error: "Could not reach " + LOAD_URL + ": "
                     + (err && err.message ? err.message
                                            : String(err)),
            };
        });
    }

    var _wired = false;
    function wirePanel(opts) {
        opts = opts || {};
        var doc = opts.doc || root.document;
        if (!doc || _wired) return;
        _wired = true;

        var input  = doc.getElementById("file-upload-input");
        var status = doc.getElementById("file-upload-status");
        if (!input) return;

        function setStatus(msg, kind) {
            if (!status) return;
            status.textContent = msg || "";
            status.className = "muted"
                + (kind === "error"   ? " is-error"   : "")
                + (kind === "loading" ? " is-loading" : "");
        }

        input.addEventListener("change", function () {
            var file = input.files && input.files[0];
            if (!file) return;
            var name = file.name || "upload";
            setStatus("Loading " + name + "…", "loading");
            var reader = new (root.FileReader || FileReader)();
            reader.onerror = function () {
                setStatus("Could not read " + name + ".", "error");
                input.value = "";
            };
            reader.onload = function () {
                var text = String(reader.result || "");
                loadText(text, name).then(function (r) {
                    input.value = "";   // allow re-selecting same file
                    if (r.ok) {
                        setStatus("Loaded " + (r.n_atoms != null
                            ? r.n_atoms + " atoms from " : "")
                            + name);
                    } else if (r.cancelled) {
                        setStatus("Kept existing workspace.");
                    } else {
                        setStatus(r.error || "Load failed.", "error");
                    }
                });
            };
            reader.readAsText(file);
        });
    }

    var api = {
        configure: configure,
        loadText:  loadText,
        wirePanel: wirePanel,
        LOAD_URL:  LOAD_URL,
    };

    if (typeof module !== "undefined" && module.exports) {
        module.exports = api;
    } else {
        root.molbuilder = root.molbuilder || {};
        root.molbuilder.structureFile = api;
        configure({
            fetch:         root.fetch
                            ? root.fetch.bind(root)
                            : undefined,
            structurePage: root.molbuilder.structurePage,
            viewerLoader:  root.molbuilder.loadStructureText,
        });
        if (root.document) {
            if (root.document.readyState === "loading") {
                root.document.addEventListener(
                    "DOMContentLoaded", function () { wirePanel(); });
            } else {
                wirePanel();
            }
        }
        if (root.molbuilder.runtime
            && typeof root.molbuilder.runtime.register === "function") {
            root.molbuilder.runtime.register(
                "structure.file", api);
        }
    }
})(typeof window !== "undefined" ? window : globalThis);
